'use strict';

const fs = require('node:fs');
const path = require('node:path');

const PLUGIN_NAME = 'ProductionModuleBoundaryPlugin';

// Keep this in step with AsyncRoute's webpackExclude magic comments. The
// context exclusion prevents accidental compilation; this expression is the
// independent, fail-closed production assertion over the final module graph.
const TEST_DIRECTORY_NAMES = new Set([
    '__tests__', '__mocks__', '__fixtures__',
    'test', 'tests', 'mock', 'mocks', 'fixture', 'fixtures'
]);
const TEST_FILE_PATTERN = /\.(?:test|spec|stories|story|bench|benchmark|fixture|mock)(?:-d)?\.[cm]?[jt]sx?$/i;
const SNAPSHOT_FILE_PATTERN = /\.snap$/i;
const PACKAGE_DIR_PATTERN = /^(.*[\\/]node_modules[\\/](?:@[^\\/]+[\\/][^\\/]+|[^\\/]+))(?:[\\/]|$)/;

function findPackageDir(resourcePath) {
    const match = resourcePath.match(PACKAGE_DIR_PATTERN);
    return match ? match[1] : null;
}

function canonicalPath(targetPath) {
    try {
        return fs.realpathSync.native(targetPath);
    } catch {
        return path.resolve(targetPath);
    }
}

function normalizeRelativePath(projectRoot, targetPath) {
    return path.relative(projectRoot, canonicalPath(targetPath)).split(path.sep).join('/');
}

function isTestResource(resourcePath) {
    return resourcePath
        .split(/[\\/]/)
        .some(segment => TEST_DIRECTORY_NAMES.has(segment.toLowerCase()))
        || TEST_FILE_PATTERN.test(resourcePath)
        || SNAPSHOT_FILE_PATTERN.test(resourcePath);
}

// Directory-based test detection (a path segment named test/, tests/,
// fixtures/ ...) holds for every resource, third-party included: no known
// package ships production code from a test directory. Filename-suffix
// detection cannot be extended the same way: core-js ships
// modules/es.regexp.test.js, the polyfill for RegExp.prototype.test that
// core-js/stable requires into every production build, and a filename
// heuristic cannot tell it from a Jest test.
function isTestDirectoryResource(resourcePath) {
    return resourcePath
        .split(/[\\/]/)
        .some(segment => TEST_DIRECTORY_NAMES.has(segment.toLowerCase()));
}

// A module is first-party when it lives in the project tree outside every
// node_modules directory. Filename-suffix test detection applies only to
// first-party files, where the convention is ours.
function isFirstPartyRelativePath(relativePath) {
    if (relativePath.startsWith('../')) {
        return false;
    }
    return !relativePath.split('/').includes('node_modules');
}

// A bare request ("entities", "@scope/pkg") is an import someone authored in
// source. Loader-emitted glue instead requires runtime files by relative path
// ("../../css-loader/dist/runtime/api.js" inside compiled CSS), and those
// paths are generated by build tooling, not chosen by a developer.
function isBareRequest(rawRequest) {
    return Boolean(rawRequest) && !rawRequest.startsWith('.') && !rawRequest.startsWith('/');
}

class ProductionModuleBoundaryPlugin {
    constructor({ projectRoot, packageLockFile, additionalResources = [] }) {
        this.projectRoot = canonicalPath(projectRoot);
        this.packageLockFile = path.resolve(packageLockFile);
        this.additionalResources = additionalResources.map(canonicalPath);
    }

    apply(compiler) {
        compiler.hooks.thisCompilation.tap(PLUGIN_NAME, compilation => {
            if (compilation.compiler !== compiler) {
                return;
            }

            compilation.hooks.finishModules.tap(PLUGIN_NAME, modules => {
                const packageLock = JSON.parse(fs.readFileSync(this.packageLockFile, 'utf8'));
                const lockPackages = packageLock.packages;
                if (!lockPackages || typeof lockPackages !== 'object') {
                    throw new Error(`${PLUGIN_NAME}: package-lock.json has no packages inventory`); // allow-raw-error: build-time assertion; webpack surfaces the message as the compile failure
                }

                const violations = [];
                const shippedPackageDirs = new Set();
                // Package roots that reached the graph through an authored
                // bare import from first-party code, or through the copied
                // asset list. These are the paths whose dev-only lock flag
                // is a real boundary violation; see the dev-only check below.
                const authoredPackageDirs = new Set();
                const inspectResource = (resource, authored) => {
                    const relativeResource = normalizeRelativePath(this.projectRoot, resource);
                    if (!relativeResource.startsWith('../')) {
                        const directoryShaped = isTestDirectoryResource(relativeResource);
                        const filenameShaped = isFirstPartyRelativePath(relativeResource)
                            && isTestResource(relativeResource);
                        if (directoryShaped || filenameShaped) {
                            violations.push(`test source: ${relativeResource}`);
                        }
                    }

                    const packageDir = findPackageDir(resource);
                    if (packageDir) {
                        shippedPackageDirs.add(packageDir);
                        if (authored) {
                            authoredPackageDirs.add(packageDir);
                        }
                    }
                };
                for (const module of modules) {
                    const resource = module.resource?.split('?')[0];
                    if (resource) {
                        const issuerRelative = module.issuer?.resource
                            ? normalizeRelativePath(this.projectRoot, module.issuer.resource.split('?')[0])
                            : null;
                        // An entry module has no issuer: its request is
                        // webpack configuration, which is authored by
                        // definition, whatever path shape the entry used.
                        const authored = issuerRelative === null
                            || (isFirstPartyRelativePath(issuerRelative) && isBareRequest(module.rawRequest));
                        inspectResource(resource, authored);
                    }
                }

                // Files copied directly into dist never enter webpack's module
                // graph. Inspect both their source paths and package roots so
                // copied tests, dev-only packages, and unknown packages cannot
                // bypass this boundary. A copy has no issuer, so its package
                // root counts as authored: nothing but intent puts a file on
                // the copy list.
                for (const resource of this.additionalResources) {
                    inspectResource(resource, true);
                }

                for (const packageDir of shippedPackageDirs) {
                    const lockKey = normalizeRelativePath(this.projectRoot, packageDir);
                    const lockEntry = lockPackages[lockKey];
                    if (!lockEntry) {
                        violations.push(`unclassified package: ${lockKey}`);
                    } else if (lockEntry.dev === true && authoredPackageDirs.has(packageDir)) {
                        // The dev-only lock flag describes what
                        // `npm ci --omit=dev` would install, not what a
                        // bundler may resolve. Two graph paths reach dev-flagged
                        // roots without anyone importing a dev dependency:
                        // loaders emit relative requires into their own
                        // runtime (css-loader, expose-loader), and hoisting
                        // leaves a dev-flagged root copy that a production
                        // package resolves by bare name (entities@2 serving
                        // markdown-it). Both are tooling artifacts. A bare
                        // request from first-party code, or an entry, is the
                        // authored import the flag polices. Residual, accepted:
                        // an author can write a relative require into
                        // node_modules (shape-identical to loader glue), and a
                        // production package can transitively resolve a
                        // dev-flagged hoisted copy; the latter fails closed in
                        // a clean --omit=dev checkout, which would not install
                        // the copy at all.
                        violations.push(`dev-only package: ${lockKey}`);
                    }
                }

                if (violations.length > 0) {
                    const details = Array.from(new Set(violations)).sort();
                    const boundaryError = new Error( // allow-raw-error: build-time assertion; webpack surfaces the message as the compile failure
                        `${PLUGIN_NAME}: refusing to compile production-only boundary violations:\n`
                        + details.map(detail => `  - ${detail}`).join('\n')
                    );
                    throw boundaryError;
                }
            });
        });
    }
}

ProductionModuleBoundaryPlugin.isTestResource = isTestResource;
ProductionModuleBoundaryPlugin.findPackageDir = findPackageDir;
ProductionModuleBoundaryPlugin.isFirstPartyRelativePath = isFirstPartyRelativePath;
ProductionModuleBoundaryPlugin.isBareRequest = isBareRequest;

module.exports = ProductionModuleBoundaryPlugin;
